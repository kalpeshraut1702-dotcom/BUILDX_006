                f"📋 *तक्रार क्र:* {ticket_id}\n"
                f"📍 *झोन:* {zone_name}\n"
                f"🏢 *विभाग:* {agency}\n"
                f"⏱️ *हमी दिलेला प्रतिसाद:* ४ तासांच्या आत\n\n"
