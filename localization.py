        if status == "reported":
            sms = f"नागपूर मनपा: प्रिय {citizen_name}, तुमची तक्रार #{ticket_id} ({zone_name}) यशस्वीपणे नोंदवली आहे. जबाबदार यंत्रणा: {agency}. ट्रॅक करा: https://nmc.gov.in/t/{ticket_id}"
